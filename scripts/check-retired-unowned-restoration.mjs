import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
const source=readFileSync("src/features/fore/publishing-trust.server.ts","utf8");
const sha=txt=>createHash("sha256").update(txt).digest("hex");
const lineage=JSON.parse(readFileSync("docs/architecture/retired-unowned-restoration-lineage.json","utf8"));
const review=JSON.parse(readFileSync("docs/architecture/canonical-writer-review.json","utf8"));
const att=JSON.parse(readFileSync("docs/architecture/retired-unowned-restoration-source-attestation-20261030.json","utf8"));
assert.equal(sha(source),JSON.parse(readFileSync("docs/architecture/retired-private-trust-owner-lineage.json","utf8")).currentSourceSha256,"New trust source must match its exact stage attestation");
assert.notEqual(sha(source),att.files[0].sha256,"Historical trust source SHA must differ from the new owner version");
assert.equal(lineage.updatedSourceSha256,att.files[0].sha256,"Historical 11-site evidence remains frozen");
assert.equal(lineage.retiredCount,11);
assert.equal(new Set(lineage.retired.map(x=>x.siteId)).size,11);
assert.equal(review.releaseApproval,false);
assert.ok(review.sites.filter(x=>x.disposition==="owner-command-required").length<=249,"Later independently reviewed retirements may only reduce unresolved count");
assert.equal(review.sites.filter(x=>x.file==="src/features/fore/publishing-trust.server.ts"&&x.disposition==="owner-command-required").length,0);
assert.ok(lineage.retired.every(x=>!review.sites.some(y=>y.siteId===x.siteId)));
assert.doesNotMatch(source,/async function (?:restore|releaseHolds)\s*\(/);
assert.doesNotMatch(source,/await (?:restore|releaseHolds)\s*\(/);
const resolve=source.slice(source.indexOf("export async function resolveRightsDispute("),source.indexOf("export async function manageRepeatInfringerPolicy("));
assert.match(resolve,/if\(x\.restoreContent\|\|x\.royaltyDisposition==="release"\)/);
const denyAt=resolve.indexOf("throw new ApiError(");
assert.ok(denyAt>=0&&resolve.includes("dispatchPrivateTrustAction"),"positive restoration must be refused before private dispatch");
const scheduler=source.slice(source.indexOf("export async function advanceRightsDisputeDeadlines("),source.indexOf("export async function leaseRightsNotificationJobs("));
assert.match(scheduler,/if \(due\.length\)[\s\S]{0,500}throw new ApiError\([\s\S]{0,60}503/);
assert.doesNotMatch(scheduler,/\.run\(|db\.batch\(|\"restored\"/);
assert.match(source,/async function takeDown\(/);
assert.match(readFileSync("src/storefront-strangler/legal-authority.worker.ts","utf8"),/if\(route==="\/trust\/private-action"\)/);
assert.match(source,/async function applyRoyaltyHold\(/);
